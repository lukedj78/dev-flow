"""The templates and the instructions design-md-to-app hands a project must obey the rules it enforces.

    python3 -m unittest test_templates

Found 2026-10-19, comparing against taste-skill v2: the shell templates hard-coded Italian copy (golden rule 2),
typed the scale as `text-[14px]` literals (which the project's own @shadcn/lint rejects) and signed the client's
public footer "Generated by design-md-to-app"; SKILL.md prescribed the same literals for the hero, nav and footer.
"""

from __future__ import annotations

import re
import unittest
from pathlib import Path

SKILL = Path(__file__).resolve().parents[1]
REFS = SKILL / "references"
SHELL = ("site-top-nav.template.tsx", "wordmark-footer.template.tsx")

ARBITRARY_TEXT = re.compile(r"\btext-\[\d")
# A JSX text node that is a word and not an expression: `>Accedi<`, `> Prodotto <`, `{count} Label<`.
# Between two tags it may span lines; after an expression it stays on one line, with no `=` — an import's
# `} from "…"` and an attribute between two expressions are not text.
LITERAL_TEXT = re.compile(r">\s*([A-Za-zÀ-ÿ][^<>{}]*?)\s*<|\}[ \t]*([A-Za-zÀ-ÿ][^<>{}\n=]*?)[ \t]*[<{]")
# An accessible name or alternative text given as a string: read aloud, so it is copy too.
LITERAL_ATTR = re.compile(r"""\b(?:aria-label|alt|title|placeholder)\s*=\s*["']([^"']+)["']""")


def visible_literals(code: str) -> list[str]:
    """Words a person reads or hears that are not t(...): JSX text and accessible-name strings, in source order."""
    found = [(m.start(), m.group(1) or m.group(2)) for m in LITERAL_TEXT.finditer(code)]
    found += [(m.start(), m.group(1)) for m in LITERAL_ATTR.finditer(code)]
    return [text for _, text in sorted(found)]


def templates() -> list[Path]:
    return sorted(p for p in REFS.glob("*.template.tsx") if "showcase" not in p.name)


class Templates(unittest.TestCase):
    def test_no_arbitrary_type_size(self) -> None:
        for path in templates():
            with self.subTest(path.name):
                self.assertIsNone(ARBITRARY_TEXT.search(path.read_text()),
                                  f"{path.name}: use the redefined --text-* slots, not text-[Npx]")

    def test_no_generator_signature_on_a_page(self) -> None:
        for path in templates():
            body = "\n".join(l for l in path.read_text().splitlines()
                             if not l.strip().startswith(("*", "//", "/*")))
            with self.subTest(path.name):
                self.assertNotIn("Generated by", body)

    def test_shell_copy_comes_from_messages(self) -> None:
        for name in SHELL:
            text = (REFS / name).read_text()
            code = "\n".join(l for l in text.splitlines() if not l.strip().startswith(("*", "//", "/*")))
            with self.subTest(name):
                self.assertEqual(visible_literals(code), [], f"{name}: visible text must be t(...)")
                self.assertRegex(code, r"getTranslations\(")


class LoadingTemplate(unittest.TestCase):
    """The skeleton the scaffold ships: on the scale, announced, translated (references/skeleton-audit.md)."""

    def setUp(self) -> None:
        self.text = (REFS / "loading.template.tsx").read_text()

    def test_sizes_are_on_the_scale(self) -> None:
        self.assertIsNone(re.search(r"\b(?:h|w|size|min-h|max-w)-\[\d", self.text), "never h-[37px] in a skeleton")

    def test_it_is_announced_with_a_translated_label(self) -> None:
        self.assertIn('role="status"', self.text)
        self.assertIn('aria-busy="true"', self.text)
        self.assertRegex(self.text, r'className="sr-only">\{t\("loading"\)\}')
        self.assertIn("skeleton-audit.md", self.text)


class Helper(unittest.TestCase):
    """visible_literals finds what a person would read or hear that is not a message."""

    def test_text_after_an_expression_and_accessible_names(self) -> None:
        code = """<p>{count} Label</p><button aria-label="Open menu" /><img alt="Logo" src="/x.png" />"""
        self.assertEqual(visible_literals(code), ["Label", "Open menu", "Logo"])

    def test_text_on_its_own_line_between_tags(self) -> None:
        self.assertEqual(visible_literals("<Button>\n  Try again\n</Button>"), ["Try again"])

    def test_messages_classes_and_aria_hidden_are_not_copy(self) -> None:
        code = """<p className="text-sm">{t("title")}</p><svg aria-hidden="true" /><img alt={t("logo")} />"""
        self.assertEqual(visible_literals(code), [])


class Instructions(unittest.TestCase):
    def setUp(self) -> None:
        self.text = (SKILL / "SKILL.md").read_text()

    def test_no_off_scale_literal_outside_the_showcase_spec(self) -> None:
        for literal in ("text-[40px]", "text-[64px]", "text-[Xpx]", "project name in `text-[14px]",
                        "text-[14px] text-on-surface-variant", "font-mono text-[11px]"):
            with self.subTest(literal):
                self.assertNotIn(literal, self.text)

    def test_no_generator_signature_demanded(self) -> None:
        self.assertNotIn("Generated by design-md-to-app from", self.text)
        self.assertNotIn("mono micro-row", self.text)
        self.assertNotIn("audit signature", self.text)


if __name__ == "__main__":
    unittest.main()
