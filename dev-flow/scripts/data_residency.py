# check


def config_regions(root: Path) -> list[tuple[str, str]]:
    """(where, region) pairs the code itself declares."""
    found = []
    for vj in [root / "vercel.json", *root.glob("apps/*/vercel.json")]:
        if vj.exists():
            try:
                d = json.loads(vj.read_text())
            except json.JSONDecodeError:
                continue
            for r in d.get("regions") or []:
                found.append((str(vj.relative_to(root)), r))
            for fn, cfg in (d.get("functions") or {}).items():
                for r in (cfg or {}).get("regions") or []:
                    found.append((f"{vj.relative_to(root)} functions[{fn}]", r))
    for env in [*root.glob(".env*.example"), *root.glob("apps/*/.env*.example"), *root.glob(".env.example")]:
        for line in env.read_text(errors="ignore").splitlines():
            m = re.match(r"\s*([A-Z0-9_]*(DATABASE_URL|POSTGRES_URL|REGION)[A-Z0-9_]*)\s*=\s*(.+)", line)
            if not m:
                continue
            value = m.group(3).strip().strip('"')
            host = re.search(r"@([^/:?]+)", value)
            region = re.search(r"((?:aws|gcp|azure)-)?[a-z]{2,}-[a-z]+-\d|fra1|cdg1|dub1|arn1|iad1|sfo1", host.group(1) if host else value)
            if region:
                found.append((f"{env.relative_to(root)} {m.group(1)}", region.group(0)))
    return found


def check(root: Path) -> dict:
    meta = load(root)
    stack = meta.get("stack") or {}
    residency = stack.get("data_residency")
    reg = (meta.get("compliance") or {}).get("sub_processors") or []
    out = {"residency": residency, "decided": residency in RESIDENCY, "warnings": [], "flags": []}
    if residency not in RESIDENCY:
        out["warnings"].append("stack.data_residency is undecided — answer the four questions (data_residency.py decide)")
        return out
    names = {r["name"] for r in reg}
    for (key, value), provider in IMPLIED.items():
        if stack.get(key) == value and provider not in names:
            out["warnings"].append(f"stack.{key} = {value!r} implies {provider}, which is not in the register")
    for r in reg:
        for f in r.get("flags") or []:
            out["flags"].append(f"{r['name']} ({r['service']}): {f}")
    if residency != "none":
        for where, region in config_regions(root):
            rc = region_class(region)
            if rc not in ("eu",):
                out["warnings"].append(f"{where} sets region {region} ({rc}) under data_residency={residency}")
    if not (root / REGISTER_MD).exists():
        out["warnings"].append(f"{REGISTER_MD} is missing — run data_residency.py render")
    return out


def cmd_check(a) -> int:
    res = check(a.root.resolve())
    if a.json:
        print(json.dumps(res, indent=2))
    else:
        print(f"data residency: {res['residency'] or 'undecided'}")
        for w in res["warnings"]:
            print(f"  ⚠ {w}")
        for f in res["flags"]:
            print(f"  ⚑ {f}")
        if not res["warnings"] and not res["flags"]:
            print("  ✓ register and config consistent with the decision")
    # warnings and flags inform; only an undecided residency is a failure
    return 0 if res["decided"] else 1


def cmd_render(a) -> int:
    root = a.root.resolve()
    render(root, load(root))
    print(f"rendered {REGISTER_MD}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("decide"); s.add_argument("root", type=Path)
    for flag in ("--eu-subjects", "--residency-obligations", "--avoid-cloud-act"):
        s.add_argument(flag, choices=["yes", "no"], required=True)
    s.add_argument("--categories", default="")
    s.add_argument("--residency", choices=RESIDENCY)
    s.add_argument("--reason")
    s = sub.add_parser("add"); s.add_argument("root", type=Path)
    for flag in ("--name", "--service", "--data"):
        s.add_argument(flag, required=True)
    s.add_argument("--region", default="")
    s.add_argument("--transfer", choices=TRANSFER, default="unknown")
    s.add_argument("--dpa"); s.add_argument("--eu-alternative"); s.add_argument("--by", default="manual")
    s.add_argument("--us-controlled", action="store_true")
    s = sub.add_parser("check"); s.add_argument("root", type=Path); s.add_argument("--json", action="store_true")
    s = sub.add_parser("render"); s.add_argument("root", type=Path)
    a = ap.parse_args(argv)
    return {"decide": cmd_decide, "add": cmd_add, "check": cmd_check, "render": cmd_render}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
