#!/usr/bin/env python3
"""Render dev-flow's routing table into dev-flow/SKILL.md from the one place it is defined.

    python3 scripts/sync_routing_table.py           # rewrite the block in SKILL.md
    python3 scripts/sync_routing_table.py --check   # exit 1 if the block is stale; write nothing

The routing table — which skill comes next, per phase and per `stack.framework` — lives in
`dev-flow/scripts/show_state.py` (COMMON_NEXT, PHASE_NEXT_BY_STACK), because that is what prints the
proposal. SKILL.md used to restate it by hand under a "keep the two in sync" comment, and they drifted
(AUDIT.md §6.6): the prose and the code disagreed on when the wireframes come, on the expo-rn gate, and
on a phase the agent stack never reaches. Now SKILL.md carries this script's rendering between two
markers, and CI fails when it is stale. Edit the dict, then run this; the pre-commit hook runs it too.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "dev-flow" / "SKILL.md"
BEGIN = ("<!-- BEGIN:routing-table — generated by scripts/sync_routing_table.py from "
         "dev-flow/scripts/show_state.py; edit the dict there, not this block -->")
END = "<!-- END:routing-table -->"
STACK_LABEL = {
    "next": "`next` (the default when `stack.framework` is missing)",
    "expo-rn": "`expo-rn`",
    "monorepo": "`monorepo`",
    "agent": "`agent` (shape ③ — no web app)",
}


def load_show_state():
    scripts = ROOT / "dev-flow" / "scripts"
    sys.path.insert(0, str(scripts))
    spec = importlib.util.spec_from_file_location("show_state_for_sync", scripts / "show_state.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render() -> str:
    ss = load_show_state()
    phases = ss.phases.PHASES
    out = [BEGIN, "", "**Every stack**", ""]
    out += [f"- `{ph}` → {ss.COMMON_NEXT[ph]}" for ph in phases if ph in ss.COMMON_NEXT]
    for fw, table in ss.PHASE_NEXT_BY_STACK.items():
        out += ["", f"**{STACK_LABEL.get(fw, f'`{fw}`')}**", ""]
        out += [f"- `{ph}` → {table[ph]}" for ph in phases if ph in table]
        skipped = [ph for ph in phases if ph not in table and ph not in ss.COMMON_NEXT]
        if skipped:
            out.append(f"- never reached on this stack: {', '.join(f'`{ph}`' for ph in skipped)}")
    out += ["", END]
    return "\n".join(out)


def replace_block(text: str, block: str) -> str:
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise SystemExit(f"{SKILL}: expected exactly one routing-table block between the markers")
    i, j = text.index(BEGIN), text.index(END) + len(END)
    return text[:i] + block + text[j:]


def main(argv: list[str]) -> int:
    text = SKILL.read_text()
    new = replace_block(text, render())
    if argv == ["--check"]:
        if new != text:
            print(f"✗ {SKILL.relative_to(ROOT)}: the routing table is stale. "
                  "Run python3 scripts/sync_routing_table.py and commit the result.")
            return 1
        print("✓ dev-flow/SKILL.md routing table matches show_state.py")
        return 0
    if argv:
        print(__doc__)
        return 2
    if new != text:
        SKILL.write_text(new)
        print("✓ dev-flow/SKILL.md routing table regenerated")
    else:
        print("✓ dev-flow/SKILL.md routing table already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
